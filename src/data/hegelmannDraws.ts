export function getHegelmannDraw(id: string) {
  return hegelmannDraws.find((item) => item.id === id);
}

export function hegelmannGroups() {
  const groups: { group: string; draws: LeagueDraw[] }[] = [];
  for (const draw of hegelmannDraws) {
    const last = groups[groups.length - 1];
    if (last && last.group === draw.group) last.draws.push(draw);
    else groups.push({ group: draw.group, draws: [draw] });
  }
  return groups;
}
